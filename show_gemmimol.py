def _build_map_js(map_info, viewer_var: str) -> str:
    kind = map_info["kind"]
    if not kind:
        return "// no density map"

    if kind == "mtz":
        cols = (json.dumps(map_info["mtz_columns"])
                if map_info["mtz_columns"] else "undefined")
        url = json.dumps(map_info["mtz_url"])
        return f"""
        try {{
          {viewer_var}.hud("loading map (MTZ)...");
          if (typeof GM.load_maps_from_mtz === "function") {{
            GM.load_maps_from_mtz(gemmi, {viewer_var}, {url}, {cols});
          }}
        }} catch (e) {{ console.error("MTZ error:", e); }}
        """

    if kind == "ccp4":
        parts = []
        if map_info["map_url"]:
            parts.append(
                f"try {{ {viewer_var}.load_map({json.dumps(map_info['map_url'])}, false); }}"
                f" catch(e) {{ console.error(e); }}"
            )
        if map_info["diff_map_url"]:
            parts.append(
                f"try {{ {viewer_var}.load_map({json.dumps(map_info['diff_map_url'])}, true); }}"
                f" catch(e) {{ console.error(e); }}"
            )
        return f"""
        {viewer_var}.hud("loading map (CCP4)...");
        {"; ".join(parts)}
        """

    if kind == "ccp4-bytes":
        b64 = map_info["map_b64"]
        return f"""
        try {{
          {viewer_var}.hud("loading map (computed)...");
          const __b64 = {json.dumps(b64)};
          const __bin = atob(__b64);
          const __u8 = new Uint8Array(__bin.length);
          for (let i = 0; i < __bin.length; i++) __u8[i] = __bin.charCodeAt(i);
          const __blob2 = new Blob([__u8], {{type:'application/octet-stream'}});
          const __mapUrl = URL.createObjectURL(__blob2);
          {viewer_var}.load_map(__mapUrl, false);
        }} catch (e) {{ console.error(e); }}
        """
    return "// unknown"


