# URL helpers
def _pdbe_updated_cif_url(pdb_id: str) -> str:
    """PDBe `_updated.cif` — Gemmi-friendly format."""
    return (f"https://www.ebi.ac.uk/pdbe/entry-files/download/"
            f"{pdb_id.lower()}_updated.cif")


def _rcsb_cif_url(pdb_id: str) -> str:
    """RCSB mmCIF — fallback if PDBe is unavailable."""
    return f"https://files.rcsb.org/download/{pdb_id.upper()}.cif"


def _pdbe_mtz_url(pdb_id: str) -> str:
    return f"https://www.ebi.ac.uk/pdbe/coordinates/files/{pdb_id.lower()}_map.mtz"


def _pdb_redo_mtz_url(pdb_id: str) -> str:
    pid = pdb_id.lower()
    return f"https://pdb-redo.eu/db/{pid}/{pid}_final.mtz"


def _cod_url(cod_id: str) -> str:
    return f"https://www.crystallography.net/cod/{cod_id.strip()}.cif"


def _ccd_url(ccd_id: str) -> str:
    ccd = ccd_id.strip().upper()
    return (
        f"https://raw.githubusercontent.com/MonomerLibrary/monomers/"
        f"master/{ccd[0].lower()}/{ccd}.cif"
    )


def _http_get_text(url: str, timeout: int = 30, retries: int = 3) -> str:
    """
    HTTP GET (text). Resistant to errors:
  - Cache: the same URL is not downloaded a second time.
  - Retries: retries up to 3 times for ConnectionReset, timeout,
    and 5xx errors (1s, 2s, 4s exponential backoff).
  - HTTPS → HTTP fallback: some academic servers may fail with TLS errors.
    """
    cached = _CACHE.get(url)
    if cached is not None:
        return cached

    text = _http_get_text_with_retries(url, timeout=timeout, retries=retries)
    _CACHE[url] = text
    return text


def _http_get_text_with_retries(url: str, timeout: int, retries: int) -> str:
    import time
    candidates = [url]
    # If HTTPS fails, also try HTTP
    if url.startswith("https://"):
        candidates.append("http://" + url[len("https://"):])

    last_err = None
    for candidate in candidates:
        for attempt in range(retries):
            try:
                if _HAS_REQUESTS:
                    r = requests.get(
                        candidate, timeout=timeout,
                        headers={"User-Agent": "gemmimol-notebook/1.0"},
                    )
                    r.raise_for_status()
                    return r.text
                else:
                    req = urllib.request.Request(
                        candidate,
                        headers={"User-Agent": "gemmimol-notebook/1.0"},
                    )
                    with urllib.request.urlopen(req, timeout=timeout) as resp:
                        return resp.read().decode("utf-8", errors="replace")
            except Exception as e:
                last_err = e
                # 4xx (404, 403, etc.) — no need to retry
                if _HAS_REQUESTS and isinstance(
                    e, requests.exceptions.HTTPError
                ):
                    status = getattr(e.response, "status_code", 0)
                    if 400 <= status < 500:
                        break  # stop for this candidate, move on to the next one
                # Backoff: 1s, 2s, 4s ...
                if attempt < retries - 1:
                    time.sleep(2 ** attempt)
    raise RuntimeError(
        f"URL could not be downloaded (after retries): {url}\n"
        f"Last Error: {last_err}\n"
        f"Fallback: you can download the file via browser and load it using `model_text=`."
    )


def _http_head_ok(url: str, timeout: int = 10) -> bool:
    cache_key = ("HEAD", url)
    cached = _CACHE.get(cache_key)
    if cached is not None:
        return cached
    try:
        if _HAS_REQUESTS:
            r = requests.head(
                url, timeout=timeout, allow_redirects=True,
                headers={"User-Agent": "gemmimol-notebook/1.0"},
            )
            ok = r.status_code < 400
        else:
            req = urllib.request.Request(
                url, method="HEAD",
                headers={"User-Agent": "gemmimol-notebook/1.0"},
            )
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                ok = 200 <= resp.status < 400
    except Exception:
        ok = False
    _CACHE[cache_key] = ok
    return ok


