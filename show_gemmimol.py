def _log(msg: str):
    print(msg)


def _resolve_model(model_url, model_text, pdb_id, cod_id, ccd_id, code,
                   verbose=True):
    """
    Returns: (label, text, resolved_pdb_or_None, source_kind_hint)
    For PDB: PDBe `_updated.cif` is preferred, RCSB is fallback.
    """
    if code is not None and not (pdb_id or cod_id or ccd_id
                                 or model_url or model_text):
        c = code.strip()
        upper = c.upper()
        if upper.startswith("PDB:"):
            pdb_id = upper.split(":", 1)[1]
        elif upper.startswith("COD:"):
            cod_id = upper.split(":", 1)[1]
        elif upper.startswith(("CCD:", "LIG:")):
            ccd_id = upper.split(":", 1)[1]
        elif c.isdigit():
            cod_id = c
        elif len(c) == 4 and c.isalnum():
            pdb_id = upper
        elif 1 <= len(c) <= 3 and c.isalnum():
            ccd_id = upper
        else:
            raise ValueError(f"Kod '{code}' tanınmadı.")

    if model_text is not None:
        return ("LOCAL", model_text, None, "auto")

    if model_url is not None:
        text = _http_get_text(model_url)
        label = os.path.splitext(os.path.basename(model_url))[0].upper() or "MODEL"
        return (label, text, None, "auto")

    if pdb_id is not None:
        pdb_id = pdb_id.strip().upper()
        # Try PDBe _updated.cif first (Gemmi-friendly)
        try:
            url = _pdbe_updated_cif_url(pdb_id)
            if verbose:
                _log(f"Downloading from PDBe: {url}")
            text = _http_get_text(url)
            return (f"PDB {pdb_id}", text, pdb_id, "macro")
        except Exception as e:
            if verbose:
                _log(f"PDBe download failed ({e}), trying RCSB...")
            text = _http_get_text(_rcsb_cif_url(pdb_id))
            return (f"PDB {pdb_id}", text, pdb_id, "macro")

    if cod_id is not None:
        cod_id = cod_id.strip()
        text = _http_get_text(_cod_url(cod_id))
        return (f"COD {cod_id}", text, None, "small")

    if ccd_id is not None:
        ccd_id = ccd_id.strip().upper()
        text = _http_get_text(_ccd_url(ccd_id))
        return (f"CCD {ccd_id}", text, None, "monomer")

    raise ValueError("No model source provided.")


def _resolve_density(cif_text, resolved_pdb,
                     mtz_url, mtz_columns, map_url, diff_map_url, map_bytes,
                     auto_density, fallback_compute,
                     auto_compute_for_small,
                     d_min, source_kind, verbose):
    """

    Density loading strategy :
    1) Directly provided URL/bytes
    2) Small molecule → computed map
    3) PDB macromolecule → PDBe MTZ → fallback PDB-REDO MTZ
    4) Last resort → compute from model (slow)
    """
    info = {
        "kind": None, "mtz_url": None, "mtz_columns": None,
        "map_url": None, "diff_map_url": None, "map_b64": None,
        "label": "",
    }

    # 1) Explicitly provided sources
    if map_bytes is not None:
        info["kind"] = "ccp4-bytes"
        info["map_b64"] = base64.b64encode(map_bytes).decode("ascii")
        info["label"] = "local CCP4 map"
        return info

    if mtz_url:
        info["kind"] = "mtz"
        info["mtz_url"] = mtz_url
        info["mtz_columns"] = list(mtz_columns) if mtz_columns else None
        info["label"] = f"MTZ ({mtz_url.split('/')[-1]})"
        return info

    if map_url or diff_map_url:
        info["kind"] = "ccp4"
        info["map_url"] = map_url
        info["diff_map_url"] = diff_map_url
        info["label"] = "CCP4 map URL"
        return info

    # 2) Small molecule → compute from model
    if source_kind in ("small", "monomer"):
        if auto_compute_for_small:
            if verbose:
                _log(f"Density is calculated for the small molecule (d_min={d_min} Å)...")
            ccp4 = _compute_ccp4_from_structure(cif_text, d_min=d_min)
            if ccp4:
                info["kind"] = "ccp4-bytes"
                info["map_b64"] = base64.b64encode(ccp4).decode("ascii")
                info["label"] = f"calculated 2Fo-Fc map (d_min={d_min} Å)"
                if verbose:
                    _log(f"{len(ccp4):,} CCP4 bytes created")
                return info
        return info

    # 3) Macromolecule → PDBe → PDB-REDO sequence
    if auto_density and resolved_pdb:
        pdbe = _pdbe_mtz_url(resolved_pdb)
        if verbose:
            _log(f"Searching PDBe MTZ: {pdbe}")
        if _http_head_ok(pdbe):
            info["kind"] = "mtz"
            info["mtz_url"] = pdbe
            info["label"] = f"PDBe MTZ ({resolved_pdb})"
            if verbose:
                _log("PDBe MTZ found")
            return info

        # PDB-REDO fallback (important for newer structures)
        redo = _pdb_redo_mtz_url(resolved_pdb)
        if verbose:
            _log(f"Not found in PDBe. Searching PDB-REDO: {redo}")
        if _http_head_ok(redo):
            info["kind"] = "mtz"
            info["mtz_url"] = redo
            info["label"] = f"PDB-REDO MTZ ({resolved_pdb})"
            if verbose:
                _log("PDB-REDO MTZ found")
            return info

        if verbose:
            _log("Neither PDBe nor PDB-REDO MTZ was found")

    # 4) Last resort
    if fallback_compute:
        if verbose:
            _log(f"Density is calculated from the model (d_min={d_min} Å)...")
        ccp4 = _compute_ccp4_from_structure(cif_text, d_min=d_min)
        if ccp4:
            info["kind"] = "ccp4-bytes"
            info["map_b64"] = base64.b64encode(ccp4).decode("ascii")
            info["label"] = f"calculated map (d_min={d_min} Å)"
            return info

    return info

