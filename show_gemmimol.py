# CIF NORMALIZATION (Gemmi WASM-compatible)

def _normalize_cif(cif_text: str, kind_hint: str = "auto"):
    """
    Returns: (normalized_text, detected_kind, extracted_pdb_id_or_None)
    """
    try:
        import gemmi
    except ImportError:
        return cif_text, "raw", None

    tmp = None
    try:
        suffix = ".cif"
        if cif_text.lstrip().startswith(("HEADER", "ATOM ", "HETATM", "TITLE",
                                          "REMARK", "CRYST1")):
            suffix = ".pdb"

        with tempfile.NamedTemporaryFile(
            mode="w", suffix=suffix, delete=False, encoding="utf-8"
        ) as f:
            f.write(cif_text)
            tmp = f.name

        # 1) MACROMOLECULE ATTEMPT
        if kind_hint in ("auto", "macro"):
            try:
                st = gemmi.read_structure(tmp, merge_chain_parts=True)
                if st and len(st) > 0:
                    extracted_pdb = _extract_pdb_id(cif_text, suffix)
                    try:
                        st.setup_entities()
                    except Exception:
                        pass
                    with tempfile.NamedTemporaryFile(
                        mode="w", suffix=".cif", delete=False, encoding="utf-8"
                    ) as g:
                        out_path = g.name
                    try:
                        if hasattr(st, "make_mmcif_document"):
                            doc = st.make_mmcif_document()
                            doc.write_file(out_path)
                        else:
                            st.write_mmcif(out_path)
                        with open(out_path, "r", encoding="utf-8") as g:
                            normalized = g.read()
                        if normalized.strip():
                            return normalized, "macro", extracted_pdb
                    finally:
                        if os.path.exists(out_path):
                            try: os.unlink(out_path)
                            except OSError: pass
            except Exception:
                pass

        # 2) SMALL MOLECULE (COD) ATTEMPT
        if kind_hint in ("auto", "small"):
            try:
                small = None
                if hasattr(gemmi, "read_small_structure"):
                    small = gemmi.read_small_structure(tmp)
                elif hasattr(gemmi, "make_small_structure_from_block"):
                    doc = gemmi.cif.read(tmp)
                    if len(doc) > 0:
                        small = gemmi.make_small_structure_from_block(doc[0])
                if small and len(small.sites) > 0:
                    return _small_structure_to_mmcif(small), "small", None
            except Exception:
                pass

        # 3) MONOMER (CCD) ATTEMPT
        if kind_hint in ("auto", "monomer"):
            try:
                doc = gemmi.cif.read(tmp)
                if len(doc) > 0:
                    block = doc[0]
                    out = _monomer_to_mmcif(block)
                    if out:
                        return out, "monomer", None
            except Exception:
                pass

        return cif_text, "raw", None

    finally:
        if tmp and os.path.exists(tmp):
            try: os.unlink(tmp)
            except OSError: pass


def _quick_extract_pdb_id(cif_text: str):
    """
    Quick (non-parsing) search for `_entry.id` in the text.
    Only text search; does not use Gemmi — the purpose of this function
    is to decide whether "this file is a PDB", so dangerous normalization
    can be skipped.
    """
    #Search directly for `data_XXXX` in the text
    for line in cif_text.splitlines()[:50]:  #first 50 lines are sufficient
        line = line.strip()
        if line.startswith("data_"):
            name = line[5:].strip()
            if len(name) == 4 and name.isalnum():
                return name.upper()
        elif line.startswith("_entry.id"):
            parts = line.split(None, 1)
            if len(parts) == 2:
                val = parts[1].strip().strip("'").strip('"')
                if len(val) == 4 and val.isalnum():
                    return val.upper()
    return None


def _extract_pdb_id(cif_text: str, suffix: str):
    """Extract the 4-character PDB ID from mmCIF/PDB."""
    try:
        import gemmi
    except ImportError:
        return None

    # PDB format
    if suffix == ".pdb":
        for line in cif_text.splitlines():
            if line.startswith("HEADER") and len(line) >= 66:
                c = line[62:66].strip()
                if len(c) == 4 and c.isalnum():
                    return c.upper()
        return None

    # mmCIF format
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".cif", delete=False, encoding="utf-8"
        ) as f:
            f.write(cif_text)
            p = f.name
        try:
            doc = gemmi.cif.read(p)
            if len(doc) == 0:
                return None
            block = doc[0]
            try:
                val = block.find_value("_entry.id")
                if val:
                    val = val.strip().strip("'").strip('"')
                    if len(val) == 4 and val.isalnum():
                        return val.upper()
            except Exception:
                pass
            name = (block.name or "").strip()
            if len(name) == 4 and name.isalnum():
                return name.upper()
        finally:
            if os.path.exists(p):
                try: os.unlink(p)
                except OSError: pass
    except Exception:
        pass
    return None


def _small_structure_to_mmcif(small) -> str:
    """Gemmi SmallStructure → minimal mmCIF."""
    cell = small.cell
    sg = small.spacegroup_hm or "P 1"
    lines = [
        f"data_{(small.name or 'small').replace(' ', '_')}",
        f"_cell.length_a       {cell.a:.4f}",
        f"_cell.length_b       {cell.b:.4f}",
        f"_cell.length_c       {cell.c:.4f}",
        f"_cell.angle_alpha    {cell.alpha:.3f}",
        f"_cell.angle_beta     {cell.beta:.3f}",
        f"_cell.angle_gamma    {cell.gamma:.3f}",
        f"_symmetry.space_group_name_H-M  '{sg}'",
        "#",
        "loop_",
        "_atom_site.group_PDB", "_atom_site.id", "_atom_site.type_symbol",
        "_atom_site.label_atom_id", "_atom_site.label_alt_id",
        "_atom_site.label_comp_id", "_atom_site.label_asym_id",
        "_atom_site.label_entity_id", "_atom_site.label_seq_id",
        "_atom_site.Cartn_x", "_atom_site.Cartn_y", "_atom_site.Cartn_z",
        "_atom_site.occupancy", "_atom_site.B_iso_or_equiv",
        "_atom_site.auth_asym_id", "_atom_site.auth_seq_id",
    ]
    for i, site in enumerate(small.sites, start=1):
        try:
            pos = site.orth(cell)
            x, y, z = pos.x, pos.y, pos.z
        except Exception:
            try:
                pos = cell.orthogonalize(site.fract)
                x, y, z = pos.x, pos.y, pos.z
            except Exception:
                x = y = z = 0.0
        elem = (site.type_symbol or "C").strip()
        label = site.label or f"{elem}{i}"
        safe = "".join(c for c in label if c.isalnum() or c == "_")[:20] or f"A{i}"
        lines.append(
            f"HETATM {i} {elem} {safe} . LIG A 1 1 "
            f"{x:.4f} {y:.4f} {z:.4f} 1.00 20.00 A 1"
        )
    return "\n".join(lines) + "\n"


def _monomer_to_mmcif(block):
    """CCD monomer (chem_comp_atom) → minimal mmCIF."""
    try:
        import gemmi
    except ImportError:
        return None
    rows = []
    for col_set in (
        ["atom_id", "type_symbol",
         "model_Cartn_x", "model_Cartn_y", "model_Cartn_z"],
        ["atom_id", "type_symbol",
         "pdbx_model_Cartn_x_ideal",
         "pdbx_model_Cartn_y_ideal",
         "pdbx_model_Cartn_z_ideal"]
    ):
        try:
            table = block.find("_chem_comp_atom.", col_set)
            for r in table:
                try:
                    rows.append((r[0], r[1], float(r[2]), float(r[3]), float(r[4])))
                except (ValueError, IndexError):
                    continue
            if rows:
                break
        except Exception:
            continue
    if not rows:
        return None
    comp_id = (block.name.replace("comp_", "") or "LIG")[:3].upper()
    lines = [
        f"data_{comp_id}",
        "_cell.length_a 1.0", "_cell.length_b 1.0", "_cell.length_c 1.0",
        "_cell.angle_alpha 90.0", "_cell.angle_beta 90.0", "_cell.angle_gamma 90.0",
        "_symmetry.space_group_name_H-M  'P 1'",
        "#", "loop_",
        "_atom_site.group_PDB", "_atom_site.id", "_atom_site.type_symbol",
        "_atom_site.label_atom_id", "_atom_site.label_alt_id",
        "_atom_site.label_comp_id", "_atom_site.label_asym_id",
        "_atom_site.label_entity_id", "_atom_site.label_seq_id",
        "_atom_site.Cartn_x", "_atom_site.Cartn_y", "_atom_site.Cartn_z",
        "_atom_site.occupancy", "_atom_site.B_iso_or_equiv",
        "_atom_site.auth_asym_id", "_atom_site.auth_seq_id",
    ]
    for i, (atom_id, sym, x, y, z) in enumerate(rows, start=1):
        safe = "".join(c for c in atom_id if c.isalnum() or c in "_'\"")[:20] \
               or f"A{i}"
        sym = sym.strip() or "C"
        lines.append(
            f"HETATM {i} {sym} {safe} . {comp_id} A 1 1 "
            f"{x:.4f} {y:.4f} {z:.4f} 1.00 20.00 A 1"
        )
    return "\n".join(lines) + "\n"


# Calculate CCP4 from the model (for small molecules)

def _compute_ccp4_from_structure(cif_text: str, d_min: float = 2.0):
    try:
        import gemmi
    except ImportError:
        return None
    cif_tmp = ccp4_tmp = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".cif", delete=False, encoding="utf-8"
        ) as f:
            f.write(cif_text)
            cif_tmp = f.name
        st = gemmi.read_structure(cif_tmp)
        if not st or not st[0]:
            return None
        dencalc = gemmi.DensityCalculatorX()
        dencalc.d_min = d_min
        dencalc.rate = 1.5
        try:
            dencalc.set_refmac_compatible_blur(st[0])
        except Exception:
            pass
        dencalc.grid.setup_from(st)
        dencalc.put_model_density_on_grid(st[0])
        ccp4 = gemmi.Ccp4Map()
        ccp4.grid = dencalc.grid
        ccp4.update_ccp4_header()
        with tempfile.NamedTemporaryFile(suffix=".ccp4", delete=False) as f:
            ccp4_tmp = f.name
        ccp4.write_ccp4_map(ccp4_tmp)
        with open(ccp4_tmp, "rb") as f:
            return f.read()
    except Exception:
        return None
    finally:
        for p in (cif_tmp, ccp4_tmp):
            if p and os.path.exists(p):
                try: os.unlink(p)
                except OSError: pass


# Main function
def show_gemmimol(
    # model
    model_url=None,
    model_text=None,
    pdb_id=None,
    cod_id=None,
    ccd_id=None,
    code=None,
    # density
    mtz_url=None,
    mtz_columns=None,
    map_url=None,
    diff_map_url=None,
    map_bytes=None,
    auto_density=True,
    fallback_compute=False,
    auto_compute_for_small=True,
    d_min=2.0,
    # view
    width="100%",
    height="720px",
    background="#000000",
    ligand_style="ball&stick",
    ball_size=0.24,
    hydrogens=False,
    verbose=True,
):
    """
    GemmiMol notebook viewer.

    Examples :
    show_gemmimol(pdb_id="4UN4")
    show_gemmimol(code="9R1V")    # PDBe fails → PDB-REDO fallback
    show_gemmimol(code="ATP")
    show_gemmimol(code="1542540")
    show_gemmimol(model_text=open("9R1V.cif").read())
    """
    # 1) Get the model text
    model_label, raw_text, resolved_pdb, source_kind = _resolve_model(
        model_url=model_url, model_text=model_text,
        pdb_id=pdb_id, cod_id=cod_id, ccd_id=ccd_id, code=code,
        verbose=verbose,
    )

    # 2) Normalization strategy
    # IMPORTANT: PDB mmCIF files (PDBe `_updated.cif` / RCSB) can be read directly
    # by Gemmi WASM. Roundtrip normalization may remove important fields
    # (REFMAC fields, cell-MTZ relationships) and can cause spatial
    # inconsistency between density and model.
    # Therefore strategy:
    #   • If PDB ID is known + pure PDB source → keep original
    #   • If model_text contains _entry.id → keep original, extract PDB ID
    #   • COD / CCD / monomer / non-standard → normalization is required

    extracted_pdb = None
    detected_kind = source_kind

    if source_kind == "macro" and resolved_pdb:
        # Downloaded directly from PDBe/RCSB — no modifications applied
        normalized = raw_text
        extracted_pdb = resolved_pdb
        if verbose:
            _log("PDB file is kept in its original form (for density compatibility)")
    else:
        # Maybe the model_text contains a hidden PDB file — first try to extract the PDB ID
        if source_kind == "auto" and model_text is not None:
            quick_pdb = _quick_extract_pdb_id(raw_text)
            if quick_pdb:
                # PDB file — no normalization needed
                normalized = raw_text
                detected_kind = "macro"
                extracted_pdb = quick_pdb
                if verbose:
                    _log(f"PDB ID '{quick_pdb}' found in mmCIF — file is kept in its original form")
            else:
                # Full normalization
                normalized, detected_kind, extracted_pdb = _normalize_cif(
                    raw_text, kind_hint=source_kind
                )
        else:
            # COD / CCD / monomer — normalization is required
            normalized, detected_kind, extracted_pdb = _normalize_cif(
                raw_text, kind_hint=source_kind
            )

    if not resolved_pdb and extracted_pdb:
        resolved_pdb = extracted_pdb
        if verbose:
            _log(f"PDBe MTZ search enabled for '{extracted_pdb}'.")

    if verbose:
        _log(f"Model ready: {len(normalized):,} symbol(s) ({detected_kind})")

    map_info = _resolve_density(
        cif_text=normalized,
        resolved_pdb=resolved_pdb,
        mtz_url=mtz_url, mtz_columns=mtz_columns,
        map_url=map_url, diff_map_url=diff_map_url,
        map_bytes=map_bytes,
        auto_density=auto_density,
        fallback_compute=fallback_compute,
        auto_compute_for_small=auto_compute_for_small,
        d_min=d_min,
        source_kind=detected_kind,
        verbose=verbose,
    )

    ns = uuid.uuid4().hex[:10]
    html = _build_html(
        ns=ns, cif_text=normalized, model_label=model_label,
        map_info=map_info, detected_kind=detected_kind,
        width=width, height=height, background=background,
        ligand_style=ligand_style, ball_size=ball_size, hydrogens=hydrogens,
    )
    display(HTML(html))


